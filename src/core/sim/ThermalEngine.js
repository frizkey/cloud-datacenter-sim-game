/**
 * ThermalEngine.js - Datacenter thermodynamics, heat diffusion, CRAC cooling, and PUE calculations
 * Pure JS, zero DOM/Phaser coupling.
 */

import { FacilityComponentType, SIM_CONSTANTS } from './Constants.js';
import { EngineEventTypes } from '../events/EventBus.js';

export class ThermalEngine {
  /**
   * @param {import('../events/EventBus.js').EventBus} eventBus
   */
  constructor(eventBus) {
    this.eventBus = eventBus;
    this.ambientTempC = SIM_CONSTANTS.AMBIENT_ROOM_TEMP_C; // 22°C
    this.throttleTempC = SIM_CONSTANTS.THERMAL_THROTTLE_TEMP_C; // 45°C
    this.shutdownTempC = SIM_CONSTANTS.THERMAL_SHUTDOWN_TEMP_C; // 65°C
    this.pueRatio = 1.20;

    this._notifiedHotspots = new Set();
  }

  /**
   * Calculate British Thermal Units (BTU) generated per hour from wattage
   * @param {number} watts
   * @returns {number}
   */
  calculateBtuPerHour(watts) {
    return Math.round(watts * SIM_CONSTANTS.HEAT_BTU_PER_WATT_HOUR);
  }

  /**
   * Calculate dynamic PUE (Power Usage Effectiveness)
   * PUE = Total Facility Power / IT Equipment Power
   * @param {Array<Object>} facilities
   * @returns {number}
   */
  calculatePue(facilities) {
    let itPowerKw = 0;
    let facilityOverheadKw = 0;

    for (const f of facilities) {
      if (!f.isPowerActive) continue;

      const power = f.nominalPowerKw || (f.powerKw || 1.0);
      if (f.type === FacilityComponentType.SERVER_RACK_42U) {
        itPowerKw += power;
      } else {
        facilityOverheadKw += power;
      }
    }

    if (itPowerKw === 0) {
      this.pueRatio = 1.0;
      return 1.0;
    }

    const rawPue = (itPowerKw + facilityOverheadKw) / itPowerKw;
    this.pueRatio = Math.round(rawPue * 100) / 100;
    return this.pueRatio;
  }

  /**
   * Returns compute capacity throttle factor based on rack temperature
   * @param {Object} rack
   * @returns {number} 0.2 to 1.0
   */
  getThrottleFactor(rack) {
    const temp = rack.temperatureCelsius || this.ambientTempC;
    if (temp <= this.throttleTempC) {
      return 1.0;
    }
    // Linear degradation above 45°C down to 20% minimum throughput
    const penalty = (temp - this.throttleTempC) / 20.0;
    return Math.max(0.2, Math.round((1.0 - penalty) * 100) / 100);
  }

  /**
   * Step thermodynamics simulation tick
   * @param {number} deltaSec
   * @param {Array<Object>|Map<string, Object>} facilities
   */
  tick(deltaSec, facilities) {
    const facList = facilities instanceof Map ? Array.from(facilities.values()) : facilities;

    const chillers = facList.filter((f) => f.type === FacilityComponentType.CRAC_CHILLER && f.isPowerActive);
    const racks = facList.filter((f) => f.type === FacilityComponentType.SERVER_RACK_42U);

    for (const rack of racks) {
      const prevTemp = rack.temperatureCelsius || this.ambientTempC;
      const watts = rack.linkedWatts || ((rack.nominalPowerKw || 1.0) * 1000);

      // 1. Heat generated by IT workload wattage
      const heatGain = (watts / 3000) * deltaSec;

      // 2. Cooling effect from active CRAC chillers based on Euclidean distance
      let coolingEffect = 0;
      for (const crac of chillers) {
        const dist = Math.hypot(crac.isoX - rack.isoX, crac.isoY - rack.isoY);
        const effect = (crac.coolingCapacityCfm || SIM_CONSTANTS.CRAC_DEFAULT_CFM) / 2500;
        coolingEffect += (effect / Math.max(1, dist * dist)) * 2.0 * deltaSec;
      }

      // 3. Passive ambient air dissipation towards 22°C
      const ambientDissipation = (this.ambientTempC - prevTemp) * 0.05 * deltaSec;

      // Net temperature change
      let newTemp = prevTemp + heatGain - coolingEffect + ambientDissipation;
      newTemp = Math.max(this.ambientTempC - 5, newTemp); // Floor near chiller temp
      rack.temperatureCelsius = Math.round(newTemp * 100) / 100;

      // Check for thermal throttling alerts
      if (rack.temperatureCelsius >= this.throttleTempC) {
        if (!this._notifiedHotspots.has(rack.id)) {
          this._notifiedHotspots.add(rack.id);
          if (this.eventBus) {
            this.eventBus.emit(EngineEventTypes.FACILITY_HOTSPOT_ALERT, {
              componentId: rack.id,
              temperatureCelsius: rack.temperatureCelsius,
              throttleFactor: this.getThrottleFactor(rack),
            });
          }
        }
      } else if (rack.temperatureCelsius < this.throttleTempC - 2.0) {
        // Reset alert state when cooled
        this._notifiedHotspots.delete(rack.id);
      }
    }

    // Recompute PUE ratio
    this.calculatePue(facList);
  }
}
